// Pure-JS MD5 / SHA-1 / SHA-256 (hex output). Used for JA3, HASSH, certificate
// fingerprints and file hashes. Inputs: Uint8Array or string (UTF-8).

const enc = new TextEncoder();
function toBytes(x) { return typeof x === 'string' ? enc.encode(x) : x; }
function hexOf(words, le) {
  let s = '';
  for (const w of words) {
    for (let i = 0; i < 4; i++) {
      const b = le ? (w >>> (i * 8)) & 0xff : (w >>> (24 - i * 8)) & 0xff;
      s += (b < 16 ? '0' : '') + b.toString(16);
    }
  }
  return s;
}

function pad(msg, le) {
  const len = msg.length;
  const padLen = ((len + 8) >>> 6 << 6) + 64; // multiple of 64 with room for 0x80 and 8-byte length
  const out = new Uint8Array(padLen);
  out.set(msg);
  out[len] = 0x80;
  const bits = len * 8;
  const dv = new DataView(out.buffer);
  if (le) { dv.setUint32(padLen - 8, bits >>> 0, true); dv.setUint32(padLen - 4, Math.floor(bits / 4294967296), true); }
  else { dv.setUint32(padLen - 8, Math.floor(bits / 4294967296), false); dv.setUint32(padLen - 4, bits >>> 0, false); }
  return out;
}

// ---- MD5 ----
const MD5_K = new Uint32Array(64);
for (let i = 0; i < 64; i++) MD5_K[i] = Math.floor(Math.abs(Math.sin(i + 1)) * 4294967296) >>> 0;
const MD5_S = [7, 12, 17, 22, 7, 12, 17, 22, 7, 12, 17, 22, 7, 12, 17, 22, 5, 9, 14, 20, 5, 9, 14, 20, 5, 9, 14, 20, 5, 9, 14, 20, 4, 11, 16, 23, 4, 11, 16, 23, 4, 11, 16, 23, 4, 11, 16, 23, 6, 10, 15, 21, 6, 10, 15, 21, 6, 10, 15, 21, 6, 10, 15, 21];

export function md5(input) {
  const m = pad(toBytes(input), true);
  const dv = new DataView(m.buffer);
  let a0 = 0x67452301, b0 = 0xefcdab89, c0 = 0x98badcfe, d0 = 0x10325476;
  const M = new Uint32Array(16);
  for (let off = 0; off < m.length; off += 64) {
    for (let i = 0; i < 16; i++) M[i] = dv.getUint32(off + i * 4, true);
    let A = a0, B = b0, C = c0, D = d0;
    for (let i = 0; i < 64; i++) {
      let F, g;
      if (i < 16) { F = (B & C) | (~B & D); g = i; }
      else if (i < 32) { F = (D & B) | (~D & C); g = (5 * i + 1) & 15; }
      else if (i < 48) { F = B ^ C ^ D; g = (3 * i + 5) & 15; }
      else { F = C ^ (B | ~D); g = (7 * i) & 15; }
      F = (F + A + MD5_K[i] + M[g]) >>> 0;
      A = D; D = C; C = B;
      B = (B + ((F << MD5_S[i]) | (F >>> (32 - MD5_S[i])))) >>> 0;
    }
    a0 = (a0 + A) >>> 0; b0 = (b0 + B) >>> 0; c0 = (c0 + C) >>> 0; d0 = (d0 + D) >>> 0;
  }
  return hexOf([a0, b0, c0, d0], true);
}

// ---- SHA-1 ----
export function sha1(input) {
  const m = pad(toBytes(input), false);
  const dv = new DataView(m.buffer);
  let h0 = 0x67452301, h1 = 0xefcdab89, h2 = 0x98badcfe, h3 = 0x10325476, h4 = 0xc3d2e1f0;
  const w = new Uint32Array(80);
  for (let off = 0; off < m.length; off += 64) {
    for (let i = 0; i < 16; i++) w[i] = dv.getUint32(off + i * 4, false);
    for (let i = 16; i < 80; i++) { const x = w[i - 3] ^ w[i - 8] ^ w[i - 14] ^ w[i - 16]; w[i] = (x << 1) | (x >>> 31); }
    let a = h0, b = h1, c = h2, d = h3, e = h4;
    for (let i = 0; i < 80; i++) {
      let f, k;
      if (i < 20) { f = (b & c) | (~b & d); k = 0x5a827999; }
      else if (i < 40) { f = b ^ c ^ d; k = 0x6ed9eba1; }
      else if (i < 60) { f = (b & c) | (b & d) | (c & d); k = 0x8f1bbcdc; }
      else { f = b ^ c ^ d; k = 0xca62c1d6; }
      const t = (((a << 5) | (a >>> 27)) + f + e + k + w[i]) >>> 0;
      e = d; d = c; c = (b << 30) | (b >>> 2); b = a; a = t;
    }
    h0 = (h0 + a) >>> 0; h1 = (h1 + b) >>> 0; h2 = (h2 + c) >>> 0; h3 = (h3 + d) >>> 0; h4 = (h4 + e) >>> 0;
  }
  return hexOf([h0, h1, h2, h3, h4], false);
}

